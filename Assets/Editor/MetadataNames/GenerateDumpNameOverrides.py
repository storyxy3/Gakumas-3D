#!/usr/bin/env python3
"""Generate evidence-backed numeric field-name overrides for the Editor ILPP.

ILSpy prefixes leading-digit field names to make C# identifiers. Preserve the
original dump.cs assembly/type/field/type mapping as a small compile-time table
to corroborate the original DummyDll metadata. This generates no method body.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re


def main():
    here = Path(__file__).resolve().parent
    project = here.parents[2]
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--dump', type=Path, default=Path('/data/xy/gakumas/work/il2cpp-3.5.3/dump.cs'))
    p.add_argument('--output', type=Path, default=here / 'OriginalDumpFieldNames.cs')
    a = p.parse_args()
    spec = importlib.util.spec_from_file_location('dump_type_diff', project / 'Tools/dump_type_diff.py')
    parser = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(parser)
    assemblies = {'Unity.RenderPipelines.Universal.Runtime', 'Unity.RenderPipelines.Core.Runtime', 'Unity.Timeline', 'UnityEngine.UI', 'Cinemachine'}
    for definition in (project / 'Packages').glob('*/*.asmdef'):
        assemblies.add(json.loads(definition.read_text())['name'])
    image_regex = '^(?:' + '|'.join(re.escape(name + '.dll') for name in sorted(assemblies)) + ')$'
    types = parser.parse_layout(a.dump, image_regex)
    entries = []
    for (assembly, name), definition in sorted(types.items()):
        if name != '<PrivateImplementationDetails>':
            continue
        field_names = {field['name'] for field in definition['fields']}
        for field in definition['fields']:
            original = field['name']
            alias = '_' + original
            if re.fullmatch(r'[0-9][0-9A-F]{31,}', original) and alias not in field_names:
                key = assembly.removesuffix('.dll') + '|' + name + '|' + alias
                # Dumper uses . for nested type names, Cecil uses /.
                field_type = field['type'].replace('<PrivateImplementationDetails>.', '<PrivateImplementationDetails>/')
                entries.append((key, original, field_type))
    lines = ['// Generated by GenerateDumpNameOverrides.py from original Il2CppDumper evidence.',
             '// Input SHA-256: ' + hashlib.sha256(a.dump.read_bytes()).hexdigest(),
             'using System.Collections.Generic;',
             'namespace zzzzQA.Recon.MetadataNames', '{',
             '    internal static class OriginalDumpFieldNames', '    {',
             '        private static readonly Dictionary<string, string[]> Evidence = new Dictionary<string, string[]>', '        {']
    for key, original, field_type in entries:
        lines.append('            { ' + json.dumps(key) + ', new[] { ' + json.dumps(original) + ', ' + json.dumps(field_type) + ' } },')
    lines += ['        };', '',
              '        internal static bool TryGet(string assembly, string type, string field, string fieldType, out string original)', '        {',
              '            original = null;',
              '            if (!Evidence.TryGetValue(assembly + "|" + type + "|" + field, out var evidence) || evidence[1] != fieldType) return false;',
              '            original = evidence[0];',
              '            return true;', '        }', '    }', '}']
    a.output.write_text('\n'.join(lines)+'\n')
    print(f'Wrote {len(entries)} assembly/type/field/type mappings to {a.output}')

if __name__ == '__main__':
    main()
